"""Reading a PDF, because most bank statements only exist as one.

Two kinds of PDF arrive. One was generated by a bank and carries its text inside
it, where the words can be read exactly rather than guessed at. The other is a
scan or a photograph wrapped in a PDF, with no text at all, and has to be rendered
and read by the OCR like any other picture.

So the text layer is tried first and the pages are rendered only when it comes back
with nothing worth reading. That is faster, and on a digital statement it is also
more accurate than OCR could be.
"""

import numpy as np

from app.core.config import settings

from app.rules import address as rules

_MAGIC = b"%PDF-"


class PdfUnreadable(ValueError):
    """The file starts like a PDF but cannot be opened: no pages, damaged, or encrypted.

    pdfium's own error escaped from here, and an address proof that was a PDF with nothing
    in it came back as HTTP 500.
    """


def _open(data: bytes):
    import pypdfium2 as pdfium

    try:
        document = pdfium.PdfDocument(data)
        if len(document) == 0:
            document.close()
            raise PdfUnreadable("the PDF has no pages")
        return document
    except PdfUnreadable:
        raise
    except Exception as problem:  # pdfium raises PdfiumError, and others for odd files
        raise PdfUnreadable(f"the PDF could not be opened: {problem}") from None


def is_pdf(data: bytes) -> bool:
    """Is this a PDF, by what is in it rather than what it was called?

    A browser's content type is whatever the browser felt like sending, and a file
    named .pdf is not necessarily one.
    """
    return data[:1024].lstrip()[: len(_MAGIC)] == _MAGIC


def text_lines(data: bytes, max_pages: int | None = None) -> list[str]:
    """The text already inside the PDF, one line per line. Empty for a scan."""
    max_pages = max_pages or rules.PDF_MAX_PAGES
    lines: list[str] = []
    document = _open(data)
    try:
        for index in range(min(len(document), max_pages)):
            page = document[index]
            found = page.get_textpage().get_text_bounded()
            lines.extend(line.strip() for line in found.splitlines() if line.strip())
    finally:
        document.close()
    return lines


def render_pages(data: bytes, max_pages: int | None = None) -> list[np.ndarray]:
    """Each page as an image, for the OCR to read.

    Rendered at PDF_RENDER_SCALE, which is what puts the print at roughly the
    resolution the OCR was tuned on for photographs of documents.
    """
    max_pages = max_pages or rules.PDF_MAX_PAGES
    images: list[np.ndarray] = []
    document = _open(data)
    try:
        for index in range(min(len(document), max_pages)):
            page = document[index]
            width, height = page.get_size()   # points; the render is this times the scale
            side = max(width, height) * rules.PDF_RENDER_SCALE
            if side > settings.MAX_IMAGE_SIDE_PX or width * height * rules.PDF_RENDER_SCALE**2 > settings.MAX_IMAGE_PIXELS:
                raise PdfUnreadable("the PDF page is too large")
            rendered = page.render(scale=rules.PDF_RENDER_SCALE)
            # The OCR and the quality checks work in BGR, as OpenCV reads images.
            images.append(np.asarray(rendered.to_pil().convert("RGB"))[:, :, ::-1].copy())
    finally:
        document.close()
    return images
